export type StorefrontLang = "bn" | "en";

const BN_DIGITS = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];

export function toBnNumber(num: number | string): string {
  const str = String(num);
  return str.replace(/[0-9]/g, (w) => BN_DIGITS[Number(w)] || w);
}

export function formatStorePrice(amount: number, lang: StorefrontLang = "bn"): string {
  if (lang === "bn") {
    return `৳ ${toBnNumber(Math.round(amount))}`;
  }
  return `৳ ${Math.round(amount).toLocaleString()}`;
}

